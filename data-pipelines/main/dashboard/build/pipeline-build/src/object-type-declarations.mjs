// DataFabrIQ object type declarations emitter. Turns the Ops App Object types of a repo
// (data-pipelines/main/objects/<table_name>.json, as read by readObjectTypes() in assemble.mjs —
// legacy descriptors already migrated to their schema form) into one TypeScript declaration file the
// custom view projects include, so a view's data layer compiles against the exact document shapes:
// per object type an alias `<Title>` for the stored document and `<Title>ListItem` for the shape
// list and query return (the listProjection), plus one alias per `$defs` entry. build-all.mjs
// writes the output to this kit's dist/ before the view projects build.
//
// The output is a global script — no imports or exports — so the declarations are ambient wherever
// the file is included, and every declaration is a type alias, never an interface: an alias that
// shares a name with a library type is a loud duplicate-identifier error in the view's `tsc` rather
// than a silent declaration merge. A name registry seeded with the host globals (src/globals.d.ts)
// and the common DOM/ES global type names reports such a collision here, before tsc runs. `$defs`
// names are shared across the repo's object types: two types declaring the same def name declare the
// same schema for it. Node >= 20, no dependencies.

import { fail, isPlainObject, SCHEMA_REF } from './assemble.mjs';

export const OBJECT_TYPE_DECLARATIONS_FILE = 'ops-app-object-types.d.ts';

const TYPE_NAME = /^[A-Z][A-Za-z0-9]*$/;

// The names the host declares for every view project (src/globals.d.ts).
const HOST_GLOBAL_TYPE_NAMES = [
  'OpsAppObjectValue', 'OpsAppObjectJsonValue', 'OpsAppObjectSchema', 'OpsAppObjectTypeDefinition',
  'OpsAppObjectMeta', 'OpsAppObjectProperties', 'OpsAppObjectRecord', 'OpsAppObject', 'OpsAppQueryResult',
  'OpsAppObjectsListTrigger', 'OpsAppObjectGetTrigger', 'OpsAppObjectsQueryTrigger',
  'KpiDefinition', 'KpiAxisValue', 'WidgetDataResponse', 'TeamRole', 'OpsAppUserContext',
  'OpsAppDocument', 'PdfPageSize', 'OpsAppDocumentContent', 'OpsAppDocumentsListTrigger', 'OpsAppDocumentGetTrigger',
];

// Common DOM and ECMAScript global types a view project's lib (ESNext, DOM) brings into scope.
const LIBRARY_GLOBAL_TYPE_NAMES = [
  'Document', 'Node', 'Event', 'Element', 'Window', 'Map', 'Set', 'Date', 'Error', 'Promise', 'Array',
  'Object', 'String', 'Number', 'Boolean', 'Symbol', 'Function', 'Record', 'Partial', 'Pick', 'Omit',
  'Text', 'Comment', 'Range', 'Selection', 'Location', 'History', 'Storage', 'Request', 'Response',
  'Headers', 'URL', 'File', 'Blob', 'Image', 'Audio', 'Option', 'Attr',
];

const HEADER = [
  '// Generated by the DataFabrIQ repo build from data-pipelines/main/objects/*.json. Do not edit; do not commit.',
  '// One alias per object type — `<Title>` is the document a get returns and an upsert takes,',
  '// `<Title>ListItem` the projection list and query return — plus one alias per `$defs` entry. The',
  '// declarations are ambient (a global script); each custom view project\'s tsconfig includes this file.',
].join('\n');

/** PascalCase of the `[A-Za-z0-9]+` runs of a name: `fm_cases` → `FmCases`, `Saved case` → `SavedCase`. */
export function pascalCase(text) {
  return (String(text).match(/[A-Za-z0-9]+/g) ?? [])
    .map((run) => run[0].toUpperCase() + run.slice(1))
    .join('');
}

/**
 * Emits the declaration file for the canonical object type entries readObjectTypes() returns
 * (schemas already key-sorted). Name problems are reported through fail(); the text is returned
 * regardless, and is emitted even when the repo declares no object type.
 */
export function emitObjectTypeDeclarations(objectTypes) {
  const names = new Map();
  for (const name of HOST_GLOBAL_TYPE_NAMES) names.set(name, 'a host global declared in src/globals.d.ts');
  for (const name of LIBRARY_GLOBAL_TYPE_NAMES) names.set(name, 'a DOM/ES global type');
  const claim = (name, origin) => {
    const taken = names.get(name);
    if (taken !== undefined) {
      fail(`${origin}: generated type name "${name}" collides with ${taken}`);
      return false;
    }
    names.set(name, origin);
    return true;
  };

  const defs = new Map();
  const sections = [];
  for (const type of objectTypes) {
    if (!isPlainObject(type.schema) || !isPlainObject(type.schema.properties)) continue;
    const { tableName, schema } = type;
    const origin = `object type "${tableName}"`;
    const title = schema.title ?? tableName;
    const typeName = pascalCase(title);
    if (!TYPE_NAME.test(typeName)) {
      fail(`${origin}: type name "${title}" must PascalCase to an identifier matching ${TYPE_NAME}`);
      continue;
    }
    claim(typeName, origin);
    claim(`${typeName}ListItem`, `${origin} (list item)`);

    const lines = [`// data-pipelines/main/objects/${tableName}.json`];
    lines.push(...jsdoc(typeDoc(schema.description, tableName, type.versionNumber), ''));
    lines.push(`type ${typeName} = ${objectType(schema, '')};`);
    const projection = Array.isArray(type.listProjection) && type.listProjection.length > 0 ? type.listProjection : null;
    lines.push(projection === null
      ? `type ${typeName}ListItem = ${typeName};`
      : `type ${typeName}ListItem = Pick<${typeName}, ${projection.map((name) => JSON.stringify(name)).join(' | ')}>;`);

    for (const [defName, defNode] of Object.entries(isPlainObject(schema.$defs) ? schema.$defs : {})) {
      const aliasName = pascalCase(defName);
      if (!TYPE_NAME.test(aliasName)) {
        fail(`${origin}: $defs name "${defName}" must PascalCase to an identifier matching ${TYPE_NAME}`);
        continue;
      }
      const canonical = JSON.stringify(defNode);
      const existing = defs.get(aliasName);
      if (existing !== undefined) {
        if (existing.canonical !== canonical) {
          fail(`${origin}: $defs "${defName}" must declare the same schema as "${aliasName}" in ${existing.origin} (def names are shared across the repo's object types)`);
        }
        continue;
      }
      if (!claim(aliasName, `${origin} $defs "${defName}"`)) continue;
      defs.set(aliasName, { canonical, origin });
      lines.push(...jsdoc(nodeDoc(defNode), ''));
      lines.push(`type ${aliasName} = ${tsType(defNode, '')};`);
    }
    sections.push(lines.join('\n'));
  }

  return [HEADER, ...sections].join('\n\n') + '\n';
}

// ── schema node → TypeScript type ────────────────────────────────────────

/** The TypeScript type of a schema node; `indent` is the indentation of the line the type starts on. */
function tsType(node, indent) {
  if (!isPlainObject(node)) return 'unknown';
  if (typeof node.$ref === 'string') {
    const match = SCHEMA_REF.exec(node.$ref);
    return match === null ? 'unknown' : pascalCase(match[1]);
  }
  if (Array.isArray(node.enum)) return node.enum.map((value) => JSON.stringify(value)).join(' | ');
  const types = Array.isArray(node.type) ? node.type : [node.type];
  const members = types.map((type) => {
    switch (type) {
      case 'string': return 'string';
      case 'number':
      case 'integer': return 'number';
      case 'boolean': return 'boolean';
      case 'null': return 'null';
      case 'array': return `Array<${tsType(node.items, indent)}>`;
      case 'object': return objectType(node, indent);
      default: return 'unknown';
    }
  });
  return members.join(' | ');
}

/**
 * An object node: a member per declared property (`required` decides the `?`), intersected with the
 * map type when `additionalProperties` is a schema (`Record<string, T>`) or true (`Record<string, unknown>`);
 * a node with a map and no `properties` is the map type alone.
 */
function objectType(node, indent) {
  const additional = node.additionalProperties;
  let mapType = null;
  if (additional === true) mapType = 'Record<string, unknown>';
  else if (isPlainObject(additional)) mapType = `Record<string, ${tsType(additional, indent)}>`;

  if (!isPlainObject(node.properties)) return mapType ?? 'Record<string, never>';

  const required = new Set(Array.isArray(node.required) ? node.required : []);
  const memberIndent = `${indent}  `;
  const lines = ['{'];
  for (const [name, child] of Object.entries(node.properties)) {
    lines.push(...jsdoc(nodeDoc(child), memberIndent));
    lines.push(`${memberIndent}${name}${required.has(name) ? '' : '?'}: ${tsType(child, memberIndent)};`);
  }
  lines.push(`${indent}}`);
  const literal = lines.join('\n');
  return mapType === null ? literal : `${literal} & ${mapType}`;
}

// ── JSDoc ────────────────────────────────────────────────────────────────

/** The doc text of a node: its description plus the ISO8601 note for a validated string format. */
function nodeDoc(node) {
  const parts = [];
  if (isPlainObject(node)) {
    if (typeof node.description === 'string' && node.description !== '') parts.push(node.description);
    if (node.format === 'date-time') parts.push('ISO8601 date-time');
    else if (node.format === 'date') parts.push('ISO8601 date');
  }
  return parts.join(' ');
}

function typeDoc(description, tableName, versionNumber) {
  const origin = `(object type "${tableName}", version ${versionNumber})`;
  if (typeof description !== 'string' || description === '') return origin;
  return `${description}${description.includes('\n') ? '\n' : ' '}${origin}`;
}

function jsdoc(text, indent) {
  if (text === '') return [];
  const lines = text.replace(/\*\//g, '* /').split(/\r?\n/);
  if (lines.length === 1) return [`${indent}/** ${lines[0]} */`];
  return [`${indent}/**`, ...lines.map((line) => `${indent} * ${line}`.trimEnd()), `${indent} */`];
}
